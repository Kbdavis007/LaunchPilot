#!/usr/bin/env node
// Generate a D1 seed migration from the MDX posts in content/posts/, so the
// worker's /api/v1/feed.xml and /atom.xml routes (which read the blog_posts
// table) serve the same content the Pages site renders.
//
//   node scripts/seed-blog.mjs            # write migrations/0002_seed_blog_posts.sql
//   node scripts/seed-blog.mjs --check    # exit 1 if the file is out of date
//
// Re-run it whenever a post is added or edited, then commit the migration.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const postsDir = join(root, 'content', 'posts');
const outPath = join(root, 'migrations', '0002_seed_blog_posts.sql');
const check = process.argv.includes('--check');

const required = [
  'title',
  'date',
  'phase',
  'target_outcomes',
  'author',
  'summary',
  'tags',
  'reading_time_minutes',
];

const fail = (message) => {
  console.error(`seed-blog: ${message}`);
  process.exit(1);
};

const readFrontmatter = (file) => {
  const raw = readFileSync(join(postsDir, file), 'utf8');
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(raw);
  if (!match) fail(`${file} has no YAML frontmatter block`);
  const data = parseYaml(match[1]);
  for (const key of required) {
    if (data[key] === undefined) fail(`${file} is missing frontmatter field "${key}"`);
  }
  return data;
};

const sql = (value) => `'${String(value).replace(/'/g, "''")}'`;
const json = (value) => sql(JSON.stringify(value));

const toRow = (file, data) => ({
  slug: file.replace(/\.mdx$/, ''),
  title: data.title,
  published_at: data.date,
  phase: data.phase,
  target_outcomes: data.target_outcomes,
  author_name: data.author.name,
  author_role: data.author.role,
  author_handle: data.author.handle,
  summary: data.summary,
  tags: data.tags,
  reading_time_minutes: data.reading_time_minutes,
});

const posts = readdirSync(postsDir)
  .filter((file) => file.endsWith('.mdx'))
  .map((file) => toRow(file, readFrontmatter(file)))
  .sort((a, b) => (a.slug < b.slug ? -1 : 1));

if (posts.length === 0) fail(`no .mdx posts found in ${postsDir}`);

const values = posts
  .map(
    (p) =>
      `  (${sql(p.slug)}, ${sql(p.title)}, ${sql(p.published_at)}, ${sql(p.phase)}, ` +
      `${json(p.target_outcomes)}, ${sql(p.author_name)}, ${sql(p.author_role)}, ` +
      `${sql(p.author_handle)}, ${sql(p.summary)}, ${json(p.tags)}, ` +
      `${p.reading_time_minutes}, 1)`
  )
  .join(',\n');

const contents = `-- Generated by scripts/seed-blog.mjs from content/posts/*.mdx. Do not edit by hand.
-- Upserts blog metadata so the worker feeds match the Pages site.
INSERT INTO blog_posts (
  slug, title, published_at, phase, target_outcomes, author_name, author_role,
  author_handle, summary, tags, reading_time_minutes, published
) VALUES
${values}
ON CONFLICT(slug) DO UPDATE SET
  title = excluded.title,
  published_at = excluded.published_at,
  phase = excluded.phase,
  target_outcomes = excluded.target_outcomes,
  author_name = excluded.author_name,
  author_role = excluded.author_role,
  author_handle = excluded.author_handle,
  summary = excluded.summary,
  tags = excluded.tags,
  reading_time_minutes = excluded.reading_time_minutes,
  published = excluded.published;
`;

if (check) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    fail('migrations/0002_seed_blog_posts.sql is missing; run `npm run seed:blog`');
  }
  if (current !== contents) {
    fail('migrations/0002_seed_blog_posts.sql is stale; run `npm run seed:blog`');
  }
  console.log('seed-blog: up to date');
} else {
  writeFileSync(outPath, contents);
  console.log(`seed-blog: wrote ${posts.length} posts to ${outPath}`);
}
